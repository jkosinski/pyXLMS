#!/usr/bin/env python3

# pyXLMS - TESTS

import pytest


def test1():
    from pyXLMS.parser import parse_site_from_merox

    site = parse_site_from_merox("[VKYVTEGmR]", ">Cas9", 531, "K2")
    assert site["peptide"] == "VKYVTEGMR"
    assert site["peptide_position"] == 2
    assert site["proteins"] == ["Cas9"]
    assert site["protein_positions"] == [532]


@pytest.mark.parametrize(
    "protein,proteins",
    [
        # a peptide found twice in one protein, e.g. in PRIDE deposit PXD008348
        (">npl3 and >npl3@345-351", ["npl3"]),
        # a peptide shared by two proteins, e.g. in PRIDE deposit PXD009777
        (
            ">sp|P0DMV9|HS71B_HUMAN and >sp|P0DMV8|HS71A_HUMAN@345-351",
            ["sp|P0DMV9|HS71B_HUMAN", "sp|P0DMV8|HS71A_HUMAN"],
        ),
        # an empty range
        (">A and >B@", ["A", "B"]),
    ],
)
def test2(protein, proteins):
    # proteins joined by " and " are parsed without protein positions
    from pyXLMS.parser import parse_site_from_merox

    site = parse_site_from_merox("[GGYDSPR]", protein, "345", "S5")
    assert site["peptide"] == "GGYDSPR"
    assert site["peptide_position"] == 5
    assert site["proteins"] == proteins
    assert site["protein_positions"] is None


